// 산술연산자
// 수학적인 계산 덧셈 뺄셈 곱셈 나눗셈 나머지

let num1 = 10;
let num2 = 5;

console.log(num1 + num2);
console.log(num1 - num2);
console.log(num1 * num2);
console.log(num1 / num2);
console.log(num1 % num2);
console.log(num1 ^ num2);

// 증감 연산자
console.log(num1++);
console.log(num1);
console.log(++num1);
console.log(num1);

num1 = 10;

console.log(num1--);
console.log(num1);
console.log(--num1);
console.log(num1);
