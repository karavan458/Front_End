// 논리 연산자
// boolean 을 위한 연산자
// NOT OR AND

// NOT -> false -> true, true -> false
let isClicked = true;
let isOpend = false;

console.log(!isClicked);
console.log(!isOpend);

// OR
console.log(true || true);
console.log(true || false);
console.log(false || true);
console.log(false || false);

// AND
console.log(true && true);
console.log(true && false);
console.log(false && true);
console.log(false && false);
